"""Compiles the GLSL under this folder to SPIR-V and writes Spirv.inc, the uint32_t arrays
Vulkan/Pipelines/Programs.cpp embeds.

The .inc is committed: a build needs no glslang. Run this after editing a shader:

    python Compile.py [path/to/glslang.exe]

glslang is taken from the argument, else from GLSLANG in the environment, else from PATH. The
shaders #include Push.glsl, which glslang resolves relative to the source (-l enables the include
extension).
"""

import os
import shutil
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = [
    ("Ff.vert", "kFfVert"),
    ("Ff.frag", "kFfFrag"),
    ("Ui.vert", "kUiVert"),
    ("Ui.frag", "kUiFrag"),
    ("Desaturate.frag", "kDesaturateFrag"),
    ("FfSem.vert", "kFfSemVert"),
    ("FfTranslated.frag", "kFfTranslatedFrag"),
]
OUT = os.path.join(HERE, "Spirv.inc")


def find_glslang():
    if len(sys.argv) > 1:
        return sys.argv[1]
    if os.environ.get("GLSLANG"):
        return os.environ["GLSLANG"]
    for name in ("glslang", "glslangValidator"):
        found = shutil.which(name)
        if found:
            return found
    sys.exit("glslang not found: pass its path, set GLSLANG, or put it on PATH")


def main():
    glslang = find_glslang()
    names = ", ".join(source for source, _ in SHADERS)
    lines = [
        f"// Generated by Shaders/Compile.py from {names}: SPIR-V 1.0 for Vulkan 1.0,",
        "// as uint32_t words. Do not edit; edit the GLSL and run the script.",
        "",
    ]
    for source, symbol in SHADERS:
        spv = os.path.join(HERE, source + ".spv")
        subprocess.check_call([glslang, "-V", "-l", "-Os", "--target-env", "vulkan1.0", "-I" + HERE, os.path.join(HERE, source), "-o", spv])
        with open(spv, "rb") as f:
            data = f.read()
        os.remove(spv)
        if len(data) % 4:
            sys.exit(f"{source}: SPIR-V size is not a multiple of 4")
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        lines.append(f"static const uint32_t {symbol}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08X" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
